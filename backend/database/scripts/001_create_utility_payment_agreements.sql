BEGIN;

CREATE TABLE public.utility_payment_agreements
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_utility_payment_agreements PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(300) NULL,

    integration_key VARCHAR(50) NOT NULL,

    allow_information_request BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at_utc TIMESTAMPTZ NULL,

    CONSTRAINT uq_utility_payment_agreements_code
        UNIQUE (code)
);

CREATE INDEX ix_utility_payment_agreements_integration_key
    ON public.utility_payment_agreements (integration_key);

CREATE INDEX ix_utility_payment_agreements_is_active
    ON public.utility_payment_agreements (is_active);

COMMIT;
